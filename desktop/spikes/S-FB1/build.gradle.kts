// S-FB1: Room-KMP + BundledSQLiteDriver on a plain jvm() target, at the CURRENT core pins.
//
// The three pins under test are copied from /gradle/libs.versions.toml at the repo root and must
// stay equal to them (a CI step greps for drift): kotlin 2.1.0, ksp 2.1.0-1.0.29, room 2.7.1.
// sqlite-bundled defaults to the repo pin (2.7.0); `-PsqliteBundled=2.5.1` re-runs the same tests
// against the version Room 2.7.1 itself was built against (see README, "Evidence").

plugins {
    kotlin("multiplatform") version "2.1.0"
    id("com.google.devtools.ksp") version "2.1.0-1.0.29"
    id("androidx.room") version "2.7.1"
}

val roomVersion = "2.7.1"
val coroutinesVersion = "1.10.1" // = core's `coroutines`
val sqliteBundledVersion = providers.gradleProperty("sqliteBundled").orElse("2.7.0").get() // = core's `sqliteBundled`

// ---- Part B: the REAL schema, mapped (never edited) from :core-engine's source tree -------------
// No Gradle dependency on :core-engine -- the files are copied byte-for-byte into build/ and
// compiled here (the same `srcDir` mapping idea LX-1 uses). What is mapped:
//   * common: data/entity/*.kt (17 entities), data/dao/*.kt (17 DAOs), and the 7 dependency-free
//     domain files that hold the 9 enums the entities use.  => proves they are commonMain-clean.
//   * jvm:    data/Converters.kt (imports org.json + java.nio, so it CANNOT be commonMain).
val coreSrc = layout.projectDirectory.dir("../../../core-engine/src/main/java/dev/fonebrew")
val mapCommon = tasks.register<Sync>("mapCoreCommonSources") {
    from(coreSrc) {
        include("data/entity/*.kt", "data/dao/*.kt")
        include(
            "domain/curation/MessageBookmark.kt", "domain/curation/CompactionDirective.kt",
            "domain/curation/GhostBranch.kt", "domain/tasks/TaskSource.kt", "domain/tasks/TaskState.kt",
            "domain/thread/DelegationEvent.kt", "domain/thread/ThreadMarker.kt",
        )
    }
    into(layout.buildDirectory.dir("mapped-core/common"))
}
val mapJvm = tasks.register<Sync>("mapCoreJvmSources") {
    from(coreSrc) { include("data/Converters.kt") }
    into(layout.buildDirectory.dir("mapped-core/jvm"))
}

kotlin {
    jvmToolchain(17)
    jvm()

    // Room's generated `actual object <Db>Constructor` trips Kotlin 2.1's Beta warning for
    // expect/actual classes (KT-61573). A warning, not an error; silenced so a real warning is visible.
    compilerOptions { freeCompilerArgs.add("-Xexpect-actual-classes") }

    sourceSets {
        commonMain { kotlin.srcDir(mapCommon) }
        jvmMain {
            kotlin.srcDir(mapJvm)
            dependencies {
                // core's Converters.kt uses org.json (Android platform API). Same version core's tests use.
                implementation("org.json:json:20231013")
            }
        }
        commonMain.dependencies {
            implementation("androidx.room:room-runtime:$roomVersion")
            implementation("androidx.sqlite:sqlite-bundled:$sqliteBundledVersion")
            implementation("org.jetbrains.kotlinx:kotlinx-coroutines-core:$coroutinesVersion")
        }
        jvmTest.dependencies {
            implementation(kotlin("test"))
            implementation(kotlin("test-junit"))
        }
    }
}

dependencies {
    // Room's processor runs per target. There is only one target here (jvm), so one KSP config.
    add("kspJvm", "androidx.room:room-compiler:$roomVersion")
}

room {
    // Schema export lands in build/ (not committed) so the test proves it was generated by THIS
    // build, rather than finding a stale checked-in file.
    schemaDirectory(layout.buildDirectory.dir("room-schemas").get().asFile.path)
}

tasks.withType<Test>().configureEach {
    systemProperty("spike.schemaDir", layout.buildDirectory.dir("room-schemas").get().asFile.path)
    testLogging {
        events("passed", "failed", "skipped")
        showStandardStreams = false
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}
