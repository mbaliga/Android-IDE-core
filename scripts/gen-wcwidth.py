#!/usr/bin/env python3
"""Generates core-engine/.../domain/remote/term/WcWidthTable.kt from the Unicode Character
Database that ships with the Python standard library (`unicodedata`), i.e. public Unicode data.

  width 2: East Asian Width W or F, assigned code points only (unassigned reads as F in this module)
  width 0: general category Mn, Me, Cf (combining / format), plus U+200B..U+200F style Cf,
           excluding U+00AD (soft hyphen, rendered one cell by most terminals)

Run:  python3 scripts/gen-wcwidth.py > core-engine/src/main/java/dev/fonebrew/domain/remote/term/WcWidthTable.kt
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


wide = ranges(lambda c: unicodedata.east_asian_width(c) in ("W", "F") and unicodedata.category(c) != "Cn")
zero = ranges(lambda c: unicodedata.category(c) in ("Mn", "Me", "Cf") and ord(c) != 0xAD)


def fmt(rs):
    lines, cur = [], "        "
    for a, b in rs:
        item = "0x%X, 0x%X, " % (a, b)
        if len(cur) + len(item) > 100:
            lines.append(cur.rstrip()); cur = "        "
        cur += item
    lines.append(cur.rstrip())
    return "\n".join(lines)


print("package dev.fonebrew.domain.remote.term")
print()
print("// GENERATED by scripts/gen-wcwidth.py - do not edit by hand.")
print("// Source: Python unicodedata, Unicode %s (public Unicode Character Database)." % unicodedata.unidata_version)
print("// Pairs of (first, last) code points, sorted, inclusive.")
print("internal object WcWidthTable {")
print("    const val UNICODE_VERSION = \"%s\"" % unicodedata.unidata_version)
print("    /** East Asian Width W / F: two cells. */")
print("    val WIDE: IntArray = intArrayOf(")
print(fmt(wide))
print("    )")
print("    /** Mn / Me / Cf (minus soft hyphen): zero cells, attach to the previous cell. */")
print("    val ZERO: IntArray = intArrayOf(")
print(fmt(zero))
print("    )")
print("}")
