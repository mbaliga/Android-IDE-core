package dev.fonebrew.data.terminal

import dev.fonebrew.domain.terminal.Snapshot
import dev.fonebrew.domain.terminal.SnapshotMeta
import dev.fonebrew.domain.terminal.TerminalHistory
import java.io.File

/** One saved snapshot on disk. */
data class HistoryEntry(val slot: String, val meta: SnapshotMeta, val sizeBytes: Long)

/**
 * "Previous session history" on disk: one bounded plain-text file per session slot in an
 * app-private directory (see [TerminalHistory] for the format and the per-file cap). At most
 * [maxEntries] files are kept (oldest dropped), so total growth is bounded by
 * `maxEntries x ~2 MB`. Everything is deletable ([delete], [deleteAll]). Not encrypted (not
 * required by the design note), but never outside app-private storage.
 */
class TerminalHistoryStore(
    private val dir: File,
    private val maxEntries: Int = 20,
    private val maxBodyBytes: Int = TerminalHistory.DEFAULT_MAX_BODY_BYTES,
) {
    /** Writes (overwrites) the snapshot for [slot]. Returns false, never throws, on I/O failure. */
    fun save(slot: String, meta: SnapshotMeta, text: String): Boolean = runCatching {
        dir.mkdirs()
        val file = fileFor(slot)
        val tmp = File(dir, file.name + ".tmp")
        tmp.writeBytes(TerminalHistory.encode(meta, text, maxBodyBytes))
        if (!tmp.renameTo(file)) { file.delete(); check(tmp.renameTo(file)) }
        prune()
        true
    }.getOrDefault(false)

    fun list(): List<HistoryEntry> =
        (dir.listFiles { f -> f.isFile && f.name.endsWith(SUFFIX) } ?: emptyArray())
            .mapNotNull { f ->
                val snap = runCatching { TerminalHistory.decode(f.readBytes(), maxBodyBytes) }.getOrNull() ?: return@mapNotNull null
                HistoryEntry(f.name.removeSuffix(SUFFIX), snap.meta, f.length())
            }
            .sortedByDescending { it.meta.savedAtMillis }

    fun read(slot: String): Snapshot? =
        runCatching { TerminalHistory.decode(fileFor(slot).readBytes(), maxBodyBytes) }.getOrNull()

    fun delete(slot: String): Boolean = fileFor(slot).delete()

    fun deleteAll() {
        dir.listFiles()?.forEach { if (it.isFile) it.delete() }
    }

    private fun prune() {
        val files = (dir.listFiles { f -> f.isFile && f.name.endsWith(SUFFIX) } ?: return)
            .sortedByDescending { it.lastModified() }
        files.drop(maxEntries).forEach { it.delete() }
    }

    /** Slots are generated by us; still, never let one escape [dir]. */
    private fun fileFor(slot: String) = File(dir, slot.filter { it.isLetterOrDigit() || it == '-' || it == '_' } + SUFFIX)

    private companion object { const val SUFFIX = ".txt" }
}
